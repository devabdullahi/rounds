#!/usr/bin/env python3
"""Writes knowledge-base/profiles into supabase/seed_profiles.sql (loaded by `supabase db reset`).

    python3 load_profiles.py           # regenerate the seed file
    python3 load_profiles.py --apply   # also upsert into the running local database now

Only profiles that passed validation are loaded; generate-case picks from these.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROFILES = ROOT / "knowledge-base" / "profiles"
SEED = ROOT / "supabase" / "seed_profiles.sql"
LOCAL_DB_CONTAINER = "supabase_db_rounds"


def literal(text: str) -> str:
    """Dollar-quoted SQL literal; the tag can't appear in generated medical text."""
    tag = "$rounds_kb$"
    if tag in text:
        raise ValueError("profile text contains the dollar-quote tag")
    return f"{tag}{text}{tag}"


def array(values: list[str]) -> str:
    return "array[" + ", ".join(literal(v) for v in values) + "]::text[]" if values else "'{}'::text[]"


def upsert(profile: dict) -> str:
    t = profile["triage"]
    g = profile["generation"]
    return (
        "insert into private.condition_profiles "
        "(slug, name, primary_clerkship, clerkships, organ_systems, validation, review, profile) values ("
        f"{literal(profile['slug'])}, {literal(t['name'])}, {literal(t['primary_clerkship'])}, "
        f"{array([t['primary_clerkship'], *t['secondary_clerkships']])}, {array(t['organ_systems'])}, "
        f"{literal(g['validation']['status'])}, {literal(g['review']['status'])}, "
        f"{literal(json.dumps(profile, ensure_ascii=False))}::jsonb)\n"
        "on conflict (slug) do update set name = excluded.name, primary_clerkship = excluded.primary_clerkship, "
        "clerkships = excluded.clerkships, organ_systems = excluded.organ_systems, validation = excluded.validation, "
        "review = excluded.review, profile = excluded.profile, updated_at = now();\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()

    profiles = [json.loads(p.read_text()) for p in sorted(PROFILES.glob("*.json"))]
    passed = [p for p in profiles if p["generation"]["validation"]["status"] == "passed"]
    sql = "-- Generated by tools/kb-generate/load_profiles.py from knowledge-base/profiles. Don't edit.\n\n"
    sql += "\n".join(upsert(p) for p in passed)
    SEED.write_text(sql)
    print(f"wrote {len(passed)} of {len(profiles)} profiles (passed only) to {SEED.relative_to(ROOT)}", file=sys.stderr)

    if args.apply:
        result = subprocess.run(["docker", "exec", "-i", LOCAL_DB_CONTAINER, "psql", "-U", "postgres", "-v", "ON_ERROR_STOP=1", "-q"],
                                input=sql, capture_output=True, text=True)
        if result.returncode != 0:
            raise SystemExit(result.stderr)
        print("applied to local database", file=sys.stderr)


if __name__ == "__main__":
    main()
