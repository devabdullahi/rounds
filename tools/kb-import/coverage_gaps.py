#!/usr/bin/env python3
"""Measures which core conditions (core_conditions.json) Rounds covers, and writes a report.

For each condition: is it in our condition list (MedlinePlus), does it have a passing profile, and
does UMLS confirm it as a SNOMED CT disorder (with its ICD-10-CM codes)? SNOMED is used only to
verify; the report shows our names and public-domain ICD-10-CM codes, not SNOMED's wording, so it
can be committed.

Output: knowledge-base/coverage-gaps.md

    python3 coverage_gaps.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from common import KB, ROOT
from snomed import concept, icd10cm, key

CORE = Path(__file__).resolve().parent / "core_conditions.json"
CLERKSHIP_LABELS = {
    "internalMedicine": "Internal medicine", "surgery": "Surgery", "pediatrics": "Pediatrics", "obgyn": "OB/GYN",
    "psychiatry": "Psychiatry", "familyMedicine": "Family medicine", "neurology": "Neurology", "emergency": "Emergency medicine", "dermatology": "Dermatology",
    "neonatology": "Neonatal/perinatal",
    "nutrition": "Health nutrition",
    "ophthalmology": "Ophthalmology",
    "geriatrics": "Geriatrics",
    "nephrology": "Nephrology",
    "allergyImmunology": "Allergy & immunology",
    "urology": "Urology",
}


def norm(text: str) -> str:
    text = re.sub(r"\([^)]*\)", "", text.lower())
    text = re.sub(r"'s\b", "", text)
    return re.sub(r"[^a-z0-9]+", " ", text).strip()


def main() -> None:
    key()
    conditions = [json.loads(line) for name in ("conditions.jsonl", "conditions_core.jsonl")
                  if (KB / name).exists() for line in (KB / name).open()]
    by_name: dict[str, str] = {}
    for c in conditions:
        slug = re.sub(r"[^a-z0-9]+", "-", c["name"].lower()).strip("-")
        for n in [c["name"], *c["also_called"], *(m["name"] for m in c["mesh"])]:
            by_name.setdefault(norm(n), slug)
    profiled = set()
    for path in (KB / "profiles").glob("*.json"):
        p = json.loads(path.read_text())
        if p["generation"]["validation"]["status"] == "passed":
            profiled.add(p["slug"])

    core = json.loads(CORE.read_text())["clerkships"]
    rows: dict[str, list[dict]] = {}
    totals = {"profiled": 0, "listed": 0, "missing": 0}
    for clerkship, items in core.items():
        out = []
        for names in items:
            name = names[0]
            slug = next((by_name[norm(n)] for n in names if norm(n) in by_name), None)
            status = "profiled" if slug in profiled else "listed" if slug else "missing"
            totals[status] += 1
            entry = {"name": name, "status": status, "slug": slug}
            if status != "profiled":
                c = concept(name)
                entry["snomed_verified"] = bool(c)
                entry["icd10cm"] = [i["code"] for i in icd10cm(c["code"])][:3] if c else []
            out.append(entry)
            print(f"  {CLERKSHIP_LABELS[clerkship]}: {name}: {status}", file=sys.stderr)
        rows[clerkship] = out

    total = sum(totals.values())
    lines = [
        "# Coverage gaps: core conditions",
        "",
        "Generated by `tools/kb-import/coverage_gaps.py` from `core_conditions.json` (our own list of conditions a US medical student is expected to work up, by clerkship).",
        "",
        "- **Missing**: not in Rounds' condition list at all (MedlinePlus topics, plus core conditions added from NLM Clinical Tables by `clinical_tables.py`).",
        "- **Listed, no profile yet**: in the list, but no passing condition profile, so no patients can be generated for it yet.",
        "- **SNOMED-verified**: UMLS confirms it as a SNOMED CT US Edition disorder or finding. ICD-10-CM codes come from the UMLS crosswalk.",
        "",
        f"**Covered (has a profile): {totals['profiled']} of {total}** · listed but not profiled: {totals['listed']} · missing: {totals['missing']}",
        "",
    ]
    for clerkship, entries in rows.items():
        missing = [e for e in entries if e["status"] == "missing"]
        listed = [e for e in entries if e["status"] == "listed"]
        covered = len(entries) - len(missing) - len(listed)
        lines += [f"## {CLERKSHIP_LABELS[clerkship]}", "", f"{covered} of {len(entries)} covered.", ""]
        if missing or listed:
            lines += ["| Condition | Status | SNOMED-verified | ICD-10-CM |", "|---|---|---|---|"]
            for e in missing + listed:
                status = "Missing" if e["status"] == "missing" else "Listed, no profile yet"
                verified = "Yes" if e.get("snomed_verified") else "Not found"
                codes = ", ".join(e.get("icd10cm") or []) or "—"
                lines.append(f"| {e['name']} | {status} | {verified} | {codes} |")
            lines.append("")
        else:
            lines += ["All covered.", ""]
    out = KB / "coverage-gaps.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)}: {totals}", file=sys.stderr)


if __name__ == "__main__":
    main()
